/** Buang emoji/simbol di awal label stage (data tetap utuh utk parsing lama).
 *  Cakup blok emoji utama (1F000+), dingbats (2600-27BF), misc technical
 *  (2300-23FF, mis. ⏳), arrow (2190-21FF), dan variation selector (FE0F). */
const EMOJI_PREFIX = /^[\p{Extended_Pictographic}\u{2300}-\u{23FF}\u{2600}-\u{27BF}\u{2190}-\u{21FF}\u{FE0F}\u{20E3}]+/u;
export function plainLabel(label) {
  const s = String(label || '');
  return EMOJI_PREFIX.test(s) ? s.replace(EMOJI_PREFIX, '').replace(/^\s+/, '') : s;
}
